#!/usr/bin/env python3
"""Convert a PSF1/PSF2 console font (e.g. Terminus) into a C bitmap font
for the PaperRadio e-paper UI.

The generated table covers U+0020..U+007E and U+00A0..U+00FF (Latin-1),
which is enough for ICY "StreamTitle" metadata of most western stations.
Glyphs are stored row-major, MSB = leftmost pixel, ceil(width/8) bytes/row.

Usage:
    python3 tools/gen_font.py /usr/share/consolefonts/Lat15-TerminusBold32x16.psf.gz \
        font_terminus_32 > main/fonts/font_terminus_32.c
"""
import gzip
import struct
import sys

PSF1_MAGIC = b"\x36\x04"
PSF2_MAGIC = b"\x72\xb5\x4a\x86"

RANGES = [(0x20, 0x7E), (0xA0, 0xFF)]


def load_psf(path):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rb") as f:
        data = f.read()

    if data[:2] == PSF1_MAGIC:
        mode, charsize = data[2], data[3]
        length = 512 if (mode & 0x01) else 256
        width, height = 8, charsize
        bpg = charsize
        glyph_off = 4
        has_table = bool(mode & 0x02)
        table = data[glyph_off + length * bpg:]
        mapping = {}
        if has_table:
            idx = 0
            pos = 0
            while idx < length and pos + 1 < len(table):
                (cp,) = struct.unpack_from("<H", table, pos)
                pos += 2
                if cp == 0xFFFF:
                    idx += 1
                elif cp != 0xFFFE:
                    mapping.setdefault(cp, idx)
        else:
            mapping = {i: i for i in range(length)}
    elif data[:4] == PSF2_MAGIC:
        (_, _, hdr, flags, length, bpg, height, width) = struct.unpack_from("<4sIIIIIII", data, 0)
        glyph_off = hdr
        table = data[glyph_off + length * bpg:]
        mapping = {}
        if flags & 0x01:
            idx = 0
            pos = 0
            while idx < length and pos < len(table):
                b = table[pos]
                if b == 0xFF:
                    idx += 1
                    pos += 1
                    continue
                if b == 0xFE:  # start of sequences: skip until 0xFF
                    while pos < len(table) and table[pos] != 0xFF:
                        pos += 1
                    continue
                # decode one UTF-8 code point
                if b < 0x80:
                    n = 1
                elif b >> 5 == 0x6:
                    n = 2
                elif b >> 4 == 0xE:
                    n = 3
                else:
                    n = 4
                cp = table[pos:pos + n].decode("utf-8", errors="replace")
                pos += n
                if len(cp) == 1:
                    mapping.setdefault(ord(cp), idx)
        else:
            mapping = {i: i for i in range(length)}
    else:
        raise SystemExit(f"{path}: not a PSF font")

    glyphs = [data[glyph_off + i * bpg: glyph_off + (i + 1) * bpg] for i in range(length)]
    return width, height, glyphs, mapping


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    path, name = sys.argv[1], sys.argv[2]
    width, height, glyphs, mapping = load_psf(path)
    row_bytes = (width + 7) // 8
    fallback = mapping.get(ord("?"), 0)

    codepoints = [cp for lo, hi in RANGES for cp in range(lo, hi + 1)]
    out = []
    out.append("/* Auto-generated by tools/gen_font.py - DO NOT EDIT */")
    out.append(f"/* Source: {path.split('/')[-1]} (Terminus Font, SIL OFL 1.1) */")
    out.append('#include "gfx.h"')
    out.append("")
    out.append(f"static const uint8_t s_{name}_bitmap[] = {{")
    for cp in codepoints:
        g = glyphs[mapping.get(cp, fallback)]
        hexes = ",".join(f"0x{b:02X}" for b in g[: row_bytes * height])
        label = chr(cp) if cp != 0x5C else "backslash"
        if label in ("*", "/"):
            label = f"'{label}'"
        out.append(f"    /* U+{cp:04X} {label} */ {hexes},")
    out.append("};")
    out.append("")
    out.append(f"const gfx_font_t {name} = {{")
    out.append(f"    .width = {width},")
    out.append(f"    .height = {height},")
    out.append(f"    .row_bytes = {row_bytes},")
    out.append(f"    .bitmap = s_{name}_bitmap,")
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
